const { chromium } = require('playwright');
// Menu sections: rename, reorder, add an item. Run with: node scripts/e2e/run.js
const path = require('path');
const B = process.env.BASE || 'http://localhost:3000'; const OUT = process.env.OUT || path.join(__dirname, '.out');
require('fs').mkdirSync(OUT, { recursive: true });
(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'] });
  const errors = []; const ok = (c, m) => { if (!c) errors.push(m); console.log(c ? '✓' : '✗', m); };
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  await ctx.route('https://fonts.googleapis.com/**', (r) => r.fulfill({ body: '', contentType: 'text/css' }));
  const a = await ctx.newPage(); a.on('pageerror', (e) => errors.push(e.message));
  const answers = []; a.on('dialog', (d) => d.accept(answers.length ? answers.shift() : d.defaultValue()));
  await a.goto(B + '/admin.html'); await a.fill('#lname', 'Syakil'); await a.fill('#pass', '1234'); await a.click('#loginForm button');
  await a.waitForSelector('#storeTitle'); await a.click('.nav [data-tab="menu"]'); await a.waitForSelector('.cathead');
  answers.push('Imported Mutton (Australia)');
  await a.click('.cathead:has-text("Imported Mutton") [data-catrename]'); await a.waitForSelector('#toast:has-text("Renamed")');
  let cat = await (await fetch(B + '/api/catalog')).json();
  ok(cat.products.filter((p) => p.category === 'Imported Mutton (Australia)').length === 8 && !cat.products.some((p) => p.category === 'Imported Mutton'), 'renamed section: all 8 items moved, shop updated');
  await a.click('.cathead:has-text("Lamb Selection") [data-catmove][data-dir="-1"]'); await a.waitForSelector('#toast:has-text("Section moved")');
  cat = await (await fetch(B + '/api/catalog')).json();
  ok(JSON.stringify([...new Set(cat.products.map((p) => p.category))]) === JSON.stringify(['Local Fresh Meat', 'Lamb Selection', 'Imported Mutton (Australia)']), 'section moved up on the shop');
  await a.click('.cathead:has-text("Lamb Selection") [data-catadd]'); await a.waitForSelector('#drawer.show [data-k="category"]');
  ok((await a.inputValue('#drawer [data-k="category"]')) === 'Lamb Selection', '+ Item opens a new item in that section');
  await a.click('#drawer [data-close] >> nth=0');
  ok(!/\(new item\)/.test(await a.textContent('#menuList')), 'closing a blank new item removes it');
  // a new section for things that are not meat, sold by the bottle
  answers.push('Cooking Oil & Groceries');
  await a.click('#addSection'); await a.waitForSelector('#drawer.show [data-k="category"]');
  ok((await a.inputValue('#drawer [data-k="category"]')) === 'Cooking Oil & Groceries' && (await a.inputValue('#drawer [data-k="unit"]')) === 'pc', '+ New section asks for a name and opens its first item');
  await a.fill('#drawer [data-k="name"]', 'Sunflower Oil 5kg'); await a.fill('#drawer [data-k="price"]', '32');
  await a.selectOption('#drawer [data-k="unit"]', 'bottle'); await a.waitForSelector('#drawer [data-k="weightKg"]');
  ok((await a.inputValue('#drawer [data-k="name"]')) === 'Sunflower Oil 5kg', 'changing the unit keeps what was typed');
  await a.fill('#drawer [data-k="weightKg"]', '5');
  await a.click('#pSave'); await a.waitForSelector('#toast:has-text("Menu saved")');
  answers.push('Vegetables');
  await a.click('#addSection'); await a.waitForSelector('#drawer.show [data-k="step"]');
  await a.fill('#drawer [data-k="name"]', 'Red Onion'); await a.fill('#drawer [data-k="price"]', '6');
  await a.selectOption('#drawer [data-k="step"]', '0.25');
  await a.click('#pSave'); await a.waitForSelector('#toast:has-text("Menu saved")');
  cat = await (await fetch(B + '/api/catalog')).json();
  const oil = cat.products.find((p) => p.name === 'Sunflower Oil 5kg'); const onion = cat.products.find((p) => p.name === 'Red Onion');
  ok(oil?.unit === 'bottle' && oil.category === 'Cooking Oil & Groceries' && oil.step === 1 && onion?.unit === 'kg' && onion.step === 0.25 && onion.min === 0.25 && onion.category === 'Vegetables', 'shop has the oil (per bottle) and the onion (0.25 kg steps) in their new sections');
  ok(JSON.stringify([...new Set(cat.products.map((p) => p.category))].slice(-2)) === JSON.stringify(['Cooking Oil & Groceries', 'Vegetables']), 'new sections appear after the meat sections');
  const J = async (body) => (await fetch(B + '/api/quote', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })).json();
  let q = await J({ items: [{ productId: oil.id, qty: 4 }, { productId: onion.id, qty: 0.75 }], fulfilment: 'pickup' });
  ok(q.errors.length === 0 && q.subtotalSen === 4 * 3200 + 450 && q.weightKg === 20.75 && q.serviceType === 'CAR', `4 bottles + 0.75 kg onion: RM${q.subtotalSen / 100}, ${q.weightKg} kg, sent by ${q.serviceType}`);
  q = await J({ items: [{ productId: onion.id, qty: 0.3 }], fulfilment: 'pickup' });
  ok(q.errors.length === 1, 'amounts off the 0.25 kg step are refused');
  await a.screenshot({ path: `${OUT}/28-menu-sections.png` });
  const s = await browser.newContext({ viewport: { width: 1000, height: 700 } }); const sp = await s.newPage();
  await sp.goto(B + '/'); await sp.waitForSelector('.cat h3');
  ok(/Imported Mutton \(Australia\)/i.test(await sp.textContent('#menu')), 'shop shows the new section name');
  ok(/\/bottle/.test(await sp.textContent(`.item[data-id="${oil.id}"]`)), 'shop prices the oil per bottle');
  await sp.click(`.item[data-id="${oil.id}"] [data-quick]`); await sp.click(`.item[data-id="${oil.id}"] [data-inc]`);
  ok(/2 bottles/.test(await sp.textContent(`.item[data-id="${oil.id}"] .ctl`)), 'cart counts "2 bottles"');
  await sp.click(`.item[data-id="${onion.id}"] [data-quick]`);
  ok(/0\.25 kg/.test(await sp.textContent(`.item[data-id="${onion.id}"] .ctl`)), 'onion starts at 0.25 kg');
  ok((await sp.locator('#tabs a').count()) === 5, 'shop menu has a tab for each of the 5 sections');
  await sp.screenshot({ path: `${OUT}/29-shop-new-sections.png` });
  await browser.close();
  console.log(errors.length ? 'PROBLEMS: ' + errors.join('; ') : 'ALL GOOD');
  process.exit(errors.length ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
